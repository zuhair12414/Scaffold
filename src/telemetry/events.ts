// Telemetry event schema and envelope definitions for Scaffold IDE.
// Student code and chat text are strictly excluded from all payloads.

// Version of the event payload schema.
export const SCHEMA_VERSION = '1.0.0'

// Behavioural events describe fine-grained student interaction within the editor.
// When an opt-out preference is active, behavioural events are dropped.
export const BEHAVIOURAL_TYPES = [
  'edit',
  'paste',
  'cursor',
  'focus',
  'blur',
  'idle_start',
  'idle_end',
] as const

// Operational events record lab milestones, submissions, runs, and tutor lifecycle.
// These are preserved even when behavioral telemetry is opted out.
export const OPERATIONAL_TYPES = [
  'session_start',
  'compile',
  'run',
  'hint_request',
  'hint_shown',
  'snooze',
  'submit',
  'opt_out',
  'opt_in',
] as const

export type BehaviouralEventType = typeof BEHAVIOURAL_TYPES[number]
export type OperationalEventType = typeof OPERATIONAL_TYPES[number]
export type TelemetryEventType = BehaviouralEventType | OperationalEventType

// Individual payload structures per event type.

export interface SessionStartPayload {
  schemaVersion: string
}

export interface EditPayload {
  // Monaco model version ID to order and correlate sequential edits.
  versionId: number
  // Count of inserted characters.
  ins: number
  // Count of deleted characters.
  del: number
  // 1-based start line of the edit change range.
  startLine: number
  // True if this edit was generated by an undo operation.
  isUndo: boolean
}

export interface PastePayload {
  // Monaco model version ID after paste insertion.
  versionId: number
  // Number of characters pasted.
  chars: number
  // Number of lines spanned by the pasted content.
  lines: number
  // Hash digest of the pasted text (never the raw text).
  hash: string
  // Hashing algorithm used to compute the digest.
  hashAlg: 'sha1' | 'fallback'
  // Source classification of the paste origin.
  source: 'inside_editor' | 'outside' | 'unknown'
}

export interface CursorPayload {
  // 1-based cursor line number.
  line: number
  // 1-based cursor column number.
  col: number
}

export interface IdleStartPayload {
  // Configured idle inactivity threshold duration in milliseconds.
  thresholdMs: number
}

export interface IdleEndPayload {
  // Total elapsed inactive duration in milliseconds.
  idleMs: number
}

export interface CompilePayload {
  // True if compilation produced no errors.
  ok: boolean
  // Count of compiler errors.
  errorCount: number
  // Count of compiler warnings.
  warningCount: number
  // Classification codes from diagnostics (Diagnostic.cls values).
  errorClasses: string[]
}

export interface RunPayload {
  // Count of unit tests passed.
  passed: number
  // Count of unit tests failed.
  failed: number
}

export interface HintRequestPayload {
  // Requested disclosure ladder level (0 to 5).
  level: number
  // Reason or affordance that triggered the hint request.
  trigger: 'requested' | 'proactive' | 'escalated'
}

export interface HintShownPayload {
  // Level of hint displayed to the student.
  level: number
  // Whether output guardrail blocked or suppressed any over-disclosure.
  blocked: boolean
  // Time taken in milliseconds for the hint response to resolve.
  latencyMs: number
}

export interface SubmitPayload {
  // Count of test cases passing at the time of submission.
  testsPassed: number
}

// Maps each event type to its payload type.
export type PayloadMap = {
  session_start: SessionStartPayload
  edit: EditPayload
  paste: PastePayload
  cursor: CursorPayload
  focus: undefined
  blur: undefined
  idle_start: IdleStartPayload
  idle_end: IdleEndPayload
  compile: CompilePayload
  run: RunPayload
  hint_request: HintRequestPayload
  hint_shown: HintShownPayload
  snooze: undefined
  submit: SubmitPayload
  opt_out: undefined
  opt_in: undefined
}

// Common envelope fields required on every telemetry event.
interface BaseTelemetryEnvelope {
  // Unique identifier for the browser session.
  sessionId: string
  // Strictly increasing sequence number starting at 1.
  seq: number
  // Milliseconds since Unix epoch from Date.now().
  t: number
  // Student identifier.
  studentId: string
  // Active lab identifier.
  labId: string
  // Active question identifier within the lab.
  questionId: string
}

// Typed telemetry event discriminated by the `type` property.
export type TelemetryEventRecord = {
  [K in TelemetryEventType]: BaseTelemetryEnvelope & {
    type: K
    payload: PayloadMap[K]
  }
}[TelemetryEventType]

// Wire protocol batch structure sent from client to server.
export interface TelemetryBatchMessage {
  type: 'batch'
  sessionId: string
  events: TelemetryEventRecord[]
}

// Wire protocol acknowledgement sent from server to client.
export interface TelemetryAckMessage {
  type: 'ack'
  sessionId: string
  // Highest sequence number such that every event from 1 to upToSeq is stored.
  upToSeq: number
}
